const EASTERN_TO_WESTERN: Record<string, string> = {
  '٠': '0', '١': '1', '٢': '2', '٣': '3', '٤': '4',
  '٥': '5', '٦': '6', '٧': '7', '٨': '8', '٩': '9', '١٠': '10',
};

// Generic helper to get stroke data for either letter or number
export function getCharStrokeData(char: string): LetterStrokeData | undefined {
  if (LETTER_STROKES[char]) return LETTER_STROKES[char];
  if (NUMBER_STROKES[char]) return NUMBER_STROKES[char];
  const western = EASTERN_TO_WESTERN[char];
  if (western && NUMBER_STROKES[western]) return NUMBER_STROKES[western];
  return undefined;
}
